#!/usr/bin/python3
"""Copy the desktop app into this user's XDG data directory; no sudo or GI needed."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tempfile

from desktop_entry import desktop_quote

APP_ID = "io.github.vera.SyncWebDAVTray"
APP_NAME = "Sync WebDAV Desktop"
PACKAGE = "sync-webdav-desktop"
VERSION = "1.0.1"
SOURCE = Path(__file__).resolve().parent
MANIFEST = ".installation.json"
PRIVATE_NAME = re.compile(r"(?:^|[_.-])(?:secrets?|credentials?|tokens?|passwords?|private)(?:[_.-]|$)", re.I)


def is_runtime_path(relative: Path) -> bool:
    """Only public, flat Python modules and SVG/PNG assets belong in the app copy."""
    if PRIVATE_NAME.search(relative.name):
        return False
    if len(relative.parts) == 1:
        return (bool(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*\.py", relative.name))
                and relative.name not in {"install.py", "build.py", "bootstrap.py", "check_distribution.py"}
                and not relative.name.startswith("test_"))
    return (len(relative.parts) == 2 and relative.parts[0] == "icons"
            and bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*\.(?:svg|png)", relative.name)))


def runtime_files(source: Path | None = None) -> list[Path]:
    source = SOURCE if source is None else source
    if (source / "icons").is_symlink():
        raise ValueError(f"Runtime icons directory must not be a symlink: {source / 'icons'}")
    files = sorted([*source.glob("*.py"), *source.glob("icons/*.svg"), *source.glob("icons/*.png")])
    result = []
    for path in files:
        if not is_runtime_path(path.relative_to(source)):
            continue
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"Runtime files must be regular files, not symlinks: {path}")
        result.append(path)
    required = {"app.py", "backend.py", "desktop_entry.py", "icons/sync-webdav-online.svg"}
    missing = required - {path.relative_to(source).as_posix() for path in result}
    if missing:
        raise ValueError(f"Missing application files: {', '.join(sorted(missing))}")
    return result


def desktop_entry(program: Path, tray: bool = False) -> str:
    # GLib checks the executable before expanding Exec field codes. Keep
    # percent signs in the script argument, never in the executable path.
    return ("[Desktop Entry]\nType=Application\n"
            f"Name={APP_NAME}\n"
            "Comment=Independent, unofficial desktop app for Sync.com WebDAV\n"
            f"Exec=/usr/bin/python3 {desktop_quote(str(program))}" + (" --tray" if tray else "") + "\n"
            f"Icon={APP_ID}\nTerminal=false\nCategories=Network;\n"
            "Keywords=Sync;WebDAV;rclone;mount;cloud;\nStartupNotify=false\n"
            + ("X-GNOME-Autostart-Delay=15\n" if tray else ""))


def shell_launcher(application: Path) -> str:
    return ("#!/bin/sh\n# Generated by Sync WebDAV Desktop; do not run as root.\n"
            f"exec /usr/bin/python3 {shlex.quote(str(application / 'app.py'))} \"$@\"\n")


def xdg_home(variable: str, default: Path) -> Path:
    value = os.environ.get(variable) or str(default)
    path = Path(value)
    if not path.is_absolute():
        raise ValueError(f"{variable} must be an absolute path")
    return path


def atomic_write(path: Path, content: bytes, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".sync-desktop-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
            os.fchmod(stream.fileno(), mode)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def installed_files(application: Path) -> set[str]:
    manifest = application / MANIFEST
    if not manifest.exists():
        return set()
    if manifest.is_symlink():
        raise ValueError(f"Refusing a symlinked installation manifest: {manifest}")
    try:
        content = json.loads(manifest.read_text(encoding="utf-8"))
        names = content["files"]
        if (content["application_id"] != APP_ID or not isinstance(names, list)
                or not all(isinstance(name, str) and is_runtime_path(Path(name))
                           and Path(name).as_posix() == name for name in names)):
            raise ValueError("Invalid app installation manifest")
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise ValueError(f"Cannot safely read {manifest}: {exc}") from exc
    return set(names)


def remove_app_files(application: Path, names: set[str]) -> None:
    # Do not follow a replaced app/icons directory into unrelated user data.
    if application.is_symlink() or (application / "icons").is_symlink():
        raise ValueError(f"Refusing a symlinked installation directory: {application}")
    for name in sorted(names):
        (application / name).unlink(missing_ok=True)
    for directory in (application / "icons", application):
        try:
            directory.rmdir()
        except (FileNotFoundError, OSError):
            pass  # Preserve any unowned files in this directory.


def refresh_desktop_cache(applications: Path, data: Path) -> None:
    if applications.is_dir() and shutil.which("update-desktop-database"):
        subprocess.run(["update-desktop-database", str(applications)], check=False)
    theme = data / "icons/hicolor"
    if (theme / "index.theme").is_file() and shutil.which("gtk-update-icon-cache"):
        subprocess.run(["gtk-update-icon-cache", "-f", "-t", str(theme)], check=False)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=f"Install {APP_NAME} for the current desktop user (no sudo)")
    parser.add_argument("--uninstall", action="store_true", help="Remove this app and its launchers only")
    parser.add_argument("--no-autostart", action="store_true", help="Do not start the app at login; remove its old autostart entry")
    args = parser.parse_args(argv)
    if os.geteuid() == 0:
        parser.error("Run as your normal desktop user, not with sudo or as root")
    try:
        home = Path.home()
        data = xdg_home("XDG_DATA_HOME", home / ".local/share")
        config = xdg_home("XDG_CONFIG_HOME", home / ".config")
        application = data / PACKAGE
        launcher = home / ".local/bin" / PACKAGE
        desktop = data / "applications" / f"{APP_ID}.desktop"
        icon = data / "icons/hicolor/scalable/apps" / f"{APP_ID}.svg"
        autostart = config / "autostart" / f"{APP_ID}.desktop"
        if application.is_symlink() or (application / "icons").is_symlink():
            raise ValueError(f"Refusing a symlinked installation directory: {application}")
        previous = installed_files(application)
        if args.uninstall:
            remove_app_files(application, previous)
            (application / MANIFEST).unlink(missing_ok=True)
            try:
                application.rmdir()
            except OSError:
                pass
            for path in (launcher, desktop, icon, autostart):
                path.unlink(missing_ok=True)
            print("Removed this user's app copy, launcher, icon, and autostart entry.")
            print("Sync profiles, credentials, services, mounts, and cloud files are unchanged.")
        else:
            files = runtime_files()
            # Validate generated paths before copying any application files.
            entry = desktop_entry(application / "app.py")
            tray_entry = desktop_entry(application / "app.py", tray=True)
            wrapper = shell_launcher(application)
            desired = {path.relative_to(SOURCE).as_posix() for path in files}
            for path in files:
                atomic_write(application / path.relative_to(SOURCE), path.read_bytes())
            remove_app_files(application, previous - desired)
            atomic_write(application / MANIFEST, (json.dumps({"application_id": APP_ID,
                         "version": VERSION, "files": sorted(desired)}, indent=2) + "\n").encode())
            atomic_write(launcher, wrapper.encode(), 0o755)
            atomic_write(desktop, entry.encode())
            atomic_write(icon, (application / "icons/sync-webdav-online.svg").read_bytes())
            if args.no_autostart:
                autostart.unlink(missing_ok=True)
            else:
                atomic_write(autostart, tray_entry.encode())
            print(f"Installed {APP_NAME} {VERSION}: {application}")
            print(f"Launcher: {launcher}\nDesktop entry: {desktop}")
            print(f"Start at login: {not args.no_autostart}")
            print("The source folder may now be moved or removed. No Sync services were changed.")
        refresh_desktop_cache(desktop.parent, data)
    except (OSError, ValueError) as exc:
        parser.exit(1, f"Installation failed: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
